// Persistent POSIX sh worker over SSH stdin/stdout using only the remote `sqlite3` CLI and `base64`.
// Uses tab-delimited base64 framing so arbitrary SQL, quotes, and newlines never touch shell evaluation.

export const REMOTE_SQLITE3_SH_WORKER = [
	'b64d() {',
	'\tif base64 -d </dev/null >/dev/null 2>&1; then',
	'\t\tbase64 -d',
	'\telse',
	'\t\tbase64 -D',
	'\tfi',
	'}',
	'',
	'b64e() {',
	"\tbase64 | tr -d '\\r\\n'",
	'}',
	'',
	'SQLITE_BIN=$(command -v sqlite3)',
	'JSON_OK=0',
	'if printf "SELECT 1;\\n" | "$SQLITE_BIN" -json :memory: >/dev/null 2>&1; then',
	'\tJSON_OK=1',
	'fi',
	'if [ "$JSON_OK" != "1" ]; then',
	'\tVER=$("$SQLITE_BIN" --version 2>/dev/null | awk \'{print $1}\')',
	'\tprintf "Remote sqlite3 (%s) does not support -json (requires sqlite3 >= 3.33). Install python3 or bun on the remote host.\\n" "$VER" >&2',
	'\texit 125',
	'fi',
	'',
	'TMP_DIR=$(mktemp -d "${TMPDIR:-/tmp}/datadip-cli.XXXXXX")',
	'trap \'rm -rf "$TMP_DIR"\' EXIT',
	'',
	'printf \'{"ready":true,"runtime":"sqlite3"}\\n\'',
	'',
	"TAB=$(printf '\\t')",
	'while IFS="$TAB" read -r op id a1 a2 a3; do',
	'\t[ -n "$op" ] || continue',
	'\tif [ "$op" = "exec" ]; then',
	'\t\trw="$a1"',
	'\t\tdbp=$(printf "%s" "$a2" | b64d)',
	'\t\tcase "$dbp" in',
	'\t\t\t"~") dbp="$HOME" ;;',
	'\t\t\t"~/"*) dbp="$HOME/${dbp#~/}" ;;',
	'\t\tesac',
	'\t\tif [ ! -e "$dbp" ]; then',
	'\t\t\terr_b64=$(printf "SQLite database file not found on remote host: %s" "$dbp" | b64e)',
	'\t\t\tprintf "res\\t%s\\t1\\t\\t%s\\n" "$id" "$err_b64"',
	'\t\t\tcontinue',
	'\t\tfi',
	'\t\tout_f="$TMP_DIR/out"',
	'\t\terr_f="$TMP_DIR/err"',
	'\t\tif [ "$rw" = "1" ]; then',
	'\t\t\t{ printf ".timeout 5000\\nPRAGMA foreign_keys = ON;\\n"; printf "%s" "$a3" | b64d; printf "\\n"; } | "$SQLITE_BIN" -bail -json "$dbp" >"$out_f" 2>"$err_f"',
	'\t\telse',
	'\t\t\t{ printf ".timeout 5000\\n"; printf "%s" "$a3" | b64d; printf "\\n"; } | "$SQLITE_BIN" -readonly -bail -json "$dbp" >"$out_f" 2>"$err_f"',
	'\t\tfi',
	'\t\trc=$?',
	'\t\tout_b64=$(b64e <"$out_f")',
	'\t\terr_b64=$(b64e <"$err_f")',
	'\t\tprintf "res\\t%s\\t%s\\t%s\\t%s\\n" "$id" "$rc" "$out_b64" "$err_b64"',
	'\telif [ "$op" = "stat" ]; then',
	'\t\tdbp=$(printf "%s" "$a1" | b64d)',
	'\t\tcase "$dbp" in',
	'\t\t\t"~") dbp="$HOME" ;;',
	'\t\t\t"~/"*) dbp="$HOME/${dbp#~/}" ;;',
	'\t\tesac',
	'\t\tfsize=$(wc -c <"$dbp" 2>/dev/null | tr -d " " || echo "")',
	'\t\twsize=$(wc -c <"${dbp}-wal" 2>/dev/null | tr -d " " || echo "")',
	'\t\tssize=$(wc -c <"${dbp}-shm" 2>/dev/null | tr -d " " || echo "")',
	'\t\tout_b64=$(printf "%s\\t%s\\t%s" "$fsize" "$wsize" "$ssize" | b64e)',
	'\t\tprintf "res\\t%s\\t0\\t%s\\t\\n" "$id" "$out_b64"',
	'\telif [ "$op" = "discover" ]; then',
	'\t\tdepth="$a1"',
	'\t\t[ -n "$depth" ] || depth=4',
	'\t\troots=$(printf "%s" "$a2" | b64d)',
	'\t\t[ -n "$roots" ] || roots="$HOME"',
	'\t\tout_f="$TMP_DIR/disc"',
	'\t\t: >"$out_f"',
	'\t\told_ifs="$IFS"',
	"\t\tIFS=$(printf '\\n')",
	'\t\tfor r in $roots; do',
	'\t\t\tcase "$r" in',
	'\t\t\t\t"~") r="$HOME" ;;',
	'\t\t\t\t"~/"*) r="$HOME/${r#~/}" ;;',
	'\t\t\tesac',
	'\t\t\t[ -d "$r" ] || continue',
	'\t\t\tfind "$r" -maxdepth "$depth" -type f \\( -name "*.sqlite" -o -name "*.sqlite3" -o -name "*.db" \\) 2>/dev/null | while IFS= read -r f; do',
	'\t\t\t\thdr=$(dd if="$f" bs=15 count=1 2>/dev/null || true)',
	'\t\t\t\t[ "$hdr" = "SQLite format 3" ] || continue',
	'\t\t\t\tsz=$(wc -c <"$f" 2>/dev/null | tr -d " " || echo 0)',
	'\t\t\t\tprintf "%s\\t%s\\n" "$f" "$sz" >>"$out_f"',
	'\t\t\tdone',
	'\t\tdone',
	'\t\tIFS="$old_ifs"',
	'\t\tout_b64=$(head -n 100 "$out_f" | b64e)',
	'\t\tprintf "res\\t%s\\t0\\t%s\\t\\n" "$id" "$out_b64"',
	'\tfi',
	'done',
].join('\n')
